const DICTS: Record<LangCode, Dict> = { pt: PT, en: EN, es: ES };

@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly storage = inject(StorageService);
  private readonly document = inject(DOCUMENT, { optional: true });
  private readonly platformId = inject(PLATFORM_ID);
  private readonly KEY = 'remindme_lang';

  readonly lang = signal<LangCode>(this.detectInitial());
  readonly current = computed<LangOption>(
    () => LANGS.find(l => l.code === this.lang()) ?? LANGS[0]
  );

  constructor() {
    effect(() => {
      const code = this.lang();
      this.storage.setItem(this.KEY, code);
      if (!isPlatformBrowser(this.platformId)) return;
      const html = this.document?.documentElement;
      if (html) {
        html.lang = this.current().htmlLang;
      }
    });
  }

  t(key: string, params?: Record<string, string | number>): string {
    const dict = DICTS[this.lang()] ?? PT;
    let out = dict[key] ?? PT[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
      }
    }
    return out;
  }

  setLang(code: LangCode): void {
    if (code === this.lang()) return;
    this.lang.set(code);
  }

  private detectInitial(): LangCode {
    const saved = this.storage.getItem<LangCode | null>(this.KEY, null);
    if (saved === 'pt' || saved === 'en' || saved === 'es') return saved;

    if (isPlatformBrowser(this.platformId)) {
      const nav = typeof navigator !== 'undefined' ? navigator.language : '';
      if (nav.toLowerCase().startsWith('en')) return 'en';
      if (nav.toLowerCase().startsWith('es')) return 'es';
    }
    return 'pt';
  }
}
